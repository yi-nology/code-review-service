func PreviewSuggestionPatch(ctx context.Context, c *app.RequestContext) {
	preview, ok := buildSuggestionPatchPreview(ctx, c)
	if !ok {
		return
	}
	common.Success(c, preview)
}

func DownloadSuggestionPatch(ctx context.Context, c *app.RequestContext) {
	preview, ok := buildSuggestionPatchPreview(ctx, c)
	if !ok {
		return
	}
	filename := fmt.Sprintf("%s-suggestion.patch", preview.ReviewID)
	c.Response.Header.Set("Content-Type", "text/x-diff; charset=utf-8")
	c.Response.Header.Set("Content-Disposition", fmt.Sprintf(`attachment; filename="%s"`, filename))
	c.SetStatusCode(http.StatusOK)
	_, _ = c.WriteString(preview.Patch)
}

func CheckSuggestionPatch(ctx context.Context, c *app.RequestContext) {
	id := strings.TrimSpace(c.Param("id"))
	if id == "" {
		common.Fail(c, common.BadRequest("review id 不能为空"))
		return
	}
	record, found, err := handlerInst.reviewSvc.Get(ctx, id)
	if err != nil {
		common.Fail(c, err)
		return
	}
	if !found {
		common.Fail(c, common.NotFound("review not found"))
		return
	}
	indexes, err := parseFindingIndexes(c.Query("finding_indexes"), len(record.Response.Findings))
	if err != nil {
		common.Fail(c, common.BadRequest(err.Error()))
		return
	}
	result, found, err := handlerInst.suggestionSvc.CheckSuggestionPatch(ctx, id, indexes)
	if err != nil {
		common.Fail(c, err)
		return
	}
	if !found {
		common.Fail(c, common.NotFound("review not found"))
		return
	}
	common.Success(c, result)
}

type applySuggestionPatchReq struct {
	FindingIndexes     []int  `json:"finding_indexes"`
	Branch             string `json:"branch"`
	Push               bool   `json:"push"`
	CreateCR           bool   `json:"create_cr"`
	TargetBranch       string `json:"target_branch"`
	Title              string `json:"title"`
	Description        string `json:"description"`
	RemoveSourceBranch bool   `json:"remove_source_branch"`
}

func ApplySuggestionPatch(ctx context.Context, c *app.RequestContext) {
	id := strings.TrimSpace(c.Param("id"))
	if id == "" {
		common.Fail(c, common.BadRequest("review id 不能为空"))
		return
	}
	req, ok := common.Bind[applySuggestionPatchReq](c)
	if !ok {
		return
	}
	record, found, err := handlerInst.reviewSvc.Get(ctx, id)
	if err != nil {
		common.Fail(c, err)
		return
	}
	if !found {
		common.Fail(c, common.NotFound("review not found"))
		return
	}
	if err := validateFindingIndexes(req.FindingIndexes, len(record.Response.Findings)); err != nil {
		common.Fail(c, common.BadRequest(err.Error()))
		return
	}
	result, found, err := handlerInst.suggestionSvc.ApplySuggestionPatch(ctx, id, suggestion.SuggestionPatchApplyOptions{
		Indexes: req.FindingIndexes,
		Branch:  req.Branch,
		Push:    req.Push || req.CreateCR,
	})
	if err != nil {
		common.Fail(c, err)
		return
	}
	if !found {
		common.Fail(c, common.NotFound("review not found"))
		return
	}
	if req.CreateCR {
		if result == nil || !result.Applied || !result.Pushed {
			common.Success(c, result)
			return
		}
		cr, err := createSuggestionPatchCR(ctx, record.Request, req, result.Branch)
		if err != nil {
			result.Error = err.Error()
			common.Success(c, result)
			return
		}
		result.CRNumber = cr.Number
		result.CRURL = cr.WebURL
	}
	common.Success(c, result)
}

func createSuggestionPatchCR(ctx context.Context, svcReq domain.Request, req *applySuggestionPatchReq, sourceBranch string) (*provider_sdk.ChangeRequest, error) {
	owner, repoName, err := gitprovider.ParseRepoPath(svcReq.Repo)
	if err != nil {
		return nil, err
	}
	targetBranch := strings.TrimSpace(req.TargetBranch)
	if targetBranch == "" {
		targetBranch = resolveReviewTargetBranch(ctx, svcReq, owner, repoName)
	}
	if targetBranch == "" {
		return nil, fmt.Errorf("target_branch is required to create PR/MR")
	}
	title := strings.TrimSpace(req.Title)
	if title == "" {
		title = "Apply review suggestions"
	}
	description := strings.TrimSpace(req.Description)
	if description == "" {
		description = fmt.Sprintf("Generated by review-service from review %s.", svcReq.ReviewID)
	}
	return handlerInst.gitMgr.CreateCR(ctx, svcReq.Provider, provider_sdk.CreateCROptions{
		Owner:              owner,
		Repo:               repoName,
		Title:              title,
		Description:        description,
		SourceBranch:       sourceBranch,
		TargetBranch:       targetBranch,
		RemoveSourceBranch: req.RemoveSourceBranch,
		Labels:             []string{"review-service"},
	})
}

func resolveReviewTargetBranch(ctx context.Context, req domain.Request, owner, repoName string) string {
	number := types.ResolvePRNumber(req.Provider, req.PullRequestID, req.MergeRequestIID)
	if number == 0 {
		return ""
	}
	cr, err := handlerInst.gitMgr.GetCR(ctx, req.Provider, owner, repoName, number)
	if err != nil || cr == nil {
		return ""
	}
	return strings.TrimSpace(cr.TargetBranch)
}

func buildSuggestionPatchPreview(ctx context.Context, c *app.RequestContext) (suggestion.SuggestionPatchPreview, bool) {
	id := strings.TrimSpace(c.Param("id"))
	if id == "" {
		common.Fail(c, common.BadRequest("review id 不能为空"))
		return suggestion.SuggestionPatchPreview{}, false
	}
	record, found, err := handlerInst.reviewSvc.Get(ctx, id)
	if err != nil {
		common.Fail(c, err)
		return suggestion.SuggestionPatchPreview{}, false
	}
	if !found {
		common.Fail(c, common.NotFound("review not found"))
		return suggestion.SuggestionPatchPreview{}, false
	}
	indexes, err := parseFindingIndexes(c.Query("finding_indexes"), len(record.Response.Findings))
	if err != nil {
		common.Fail(c, common.BadRequest(err.Error()))
		return suggestion.SuggestionPatchPreview{}, false
	}
	return suggestion.BuildSuggestionPatch(record.ID, record.Response.Findings, indexes), true
}

func validateFindingIndexes(indexes []int, total int) error {
	seen := map[int]struct{}{}
	for _, idx := range indexes {
		if idx < 0 || idx >= total {
			return fmt.Errorf("finding index %d out of range", idx)
		}
		if _, ok := seen[idx]; ok {
			return fmt.Errorf("finding index %d duplicated", idx)
		}
		seen[idx] = struct{}{}
	}
	return nil
}

func parseFindingIndexes(raw string, total int) ([]int, error) {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return nil, nil
	}
	parts := strings.Split(raw, ",")
	indexes := make([]int, 0, len(parts))
	seen := make(map[int]struct{}, len(parts))
	for _, part := range parts {
		part = strings.TrimSpace(part)
		if part == "" {
			return nil, fmt.Errorf("finding_indexes 包含空值")
		}
		idx, err := strconv.Atoi(part)
		if err != nil {
			return nil, fmt.Errorf("finding_indexes 只能包含数字")
		}
		if idx < 0 || idx >= total {
			return nil, fmt.Errorf("finding index %d out of range", idx)
		}
		if _, ok := seen[idx]; ok {
			continue
		}
		seen[idx] = struct{}{}
		indexes = append(indexes, idx)
	}
	return indexes, nil
}
