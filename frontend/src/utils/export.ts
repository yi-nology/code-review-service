// Report export utilities

export interface ExportOptions {
  format: 'markdown' | 'json' | 'html'
  includeDetails: boolean
  includeFindings: boolean
  includeSummary: boolean
}

export interface ReviewReport {
  reviewId: string
  provider: string
  repo: string
  status: string
  summary: string
  score: number
  grade: string
  findings: Finding[]
  createdAt: string
  updatedAt: string
}

export interface Finding {
  severity: string
  category: string
  path: string
  line: number
  title: string
  body: string
  suggestion?: string
}

// Export report as Markdown
export function exportAsMarkdown(report: ReviewReport, options: ExportOptions): string {
  const lines: string[] = []

  // Header
  lines.push('# AI Code Review Report')
  lines.push('')
  lines.push(`**Review ID:** ${report.reviewId}`)
  lines.push(`**Repository:** ${report.repo}`)
  lines.push(`**Provider:** ${report.provider}`)
  lines.push(`**Status:** ${report.status}`)
  lines.push(`**Date:** ${new Date(report.createdAt).toLocaleDateString('zh-CN')}`)
  lines.push('')

  // Score
  if (options.includeSummary) {
    lines.push('## Score')
    lines.push('')
    lines.push(`**Score:** ${report.score}/100 (${report.grade})`)
    lines.push('')
  }

  // Summary
  if (options.includeSummary && report.summary) {
    lines.push('## Summary')
    lines.push('')
    lines.push(report.summary)
    lines.push('')
  }

  // Findings
  if (options.includeFindings && report.findings.length > 0) {
    lines.push('## Findings')
    lines.push('')
    lines.push(`Total: ${report.findings.length} findings`)
    lines.push('')

    // Group by severity
    const critical = report.findings.filter(f => f.severity === 'critical')
    const major = report.findings.filter(f => f.severity === 'major')
    const minor = report.findings.filter(f => f.severity === 'minor')
    const info = report.findings.filter(f => f.severity === 'info')

    if (critical.length > 0) {
      lines.push(`### Critical (${critical.length})`)
      lines.push('')
      critical.forEach((f, i) => {
        lines.push(`${i + 1}. **${f.title}**`)
        if (f.path) lines.push(`   - File: \`${f.path}${f.line ? `:${f.line}` : ''}\``)
        if (f.body) lines.push(`   - ${f.body}`)
        if (f.suggestion) lines.push(`   - Suggestion: ${f.suggestion}`)
        lines.push('')
      })
    }

    if (major.length > 0) {
      lines.push(`### Major (${major.length})`)
      lines.push('')
      major.forEach((f, i) => {
        lines.push(`${i + 1}. **${f.title}**`)
        if (f.path) lines.push(`   - File: \`${f.path}${f.line ? `:${f.line}` : ''}\``)
        if (f.body) lines.push(`   - ${f.body}`)
        lines.push('')
      })
    }

    if (minor.length > 0) {
      lines.push(`### Minor (${minor.length})`)
      lines.push('')
      minor.forEach((f, i) => {
        lines.push(`${i + 1}. ${f.title}`)
        if (f.path) lines.push(`   - File: \`${f.path}${f.line ? `:${f.line}` : ''}\``)
        lines.push('')
      })
    }

    if (info.length > 0) {
      lines.push(`### Info (${info.length})`)
      lines.push('')
      info.forEach((f, i) => {
        lines.push(`${i + 1}. ${f.title}`)
        lines.push('')
      })
    }
  }

  // Footer
  lines.push('---')
  lines.push('*Generated by AI Code Review Service*')

  return lines.join('\n')
}

// Export report as JSON
export function exportAsJSON(report: ReviewReport, options: ExportOptions): string {
  const data: any = {
    reviewId: report.reviewId,
    provider: report.provider,
    repo: report.repo,
    status: report.status,
    score: report.score,
    grade: report.grade,
    createdAt: report.createdAt,
    updatedAt: report.updatedAt,
  }

  if (options.includeSummary) {
    data.summary = report.summary
  }

  if (options.includeFindings) {
    data.findings = report.findings
    data.findingsCount = {
      total: report.findings.length,
      critical: report.findings.filter(f => f.severity === 'critical').length,
      major: report.findings.filter(f => f.severity === 'major').length,
      minor: report.findings.filter(f => f.severity === 'minor').length,
      info: report.findings.filter(f => f.severity === 'info').length,
    }
  }

  return JSON.stringify(data, null, 2)
}

// Export report as HTML
export function exportAsHTML(report: ReviewReport, options: ExportOptions): string {
  const markdown = exportAsMarkdown(report, options)
  
  // Simple markdown to HTML conversion
  const html = markdown
    .replace(/^### (.+)$/gm, '<h3>$1</h3>')
    .replace(/^## (.+)$/gm, '<h2>$1</h2>')
    .replace(/^# (.+)$/gm, '<h1>$1</h1>')
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/`(.+?)`/g, '<code>$1</code>')
    .replace(/^- (.+)$/gm, '<li>$1</li>')
    .replace(/^(\d+)\. (.+)$/gm, '<li>$2</li>')
    .replace(/\n\n/g, '</p><p>')
    .replace(/\n/g, '<br>')

  return `<!DOCTYPE html>
<html>
<head>
  <meta charset="UTF-8">
  <title>Code Review Report - ${report.reviewId}</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; max-width: 800px; margin: 0 auto; padding: 20px; }
    h1 { color: #333; border-bottom: 2px solid #409eff; padding-bottom: 10px; }
    h2 { color: #409eff; margin-top: 30px; }
    h3 { color: #666; }
    code { background: #f5f5f5; padding: 2px 6px; border-radius: 3px; font-family: monospace; }
    li { margin: 5px 0; }
    .critical { color: #f56c6c; }
    .major { color: #e6a23c; }
    .minor { color: #409eff; }
    .info { color: #909399; }
  </style>
</head>
<body>
  <p>${html}</p>
</body>
</html>`
}

// Download file
export function downloadFile(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = filename
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  URL.revokeObjectURL(url)
}

// Export report
export function exportReport(report: ReviewReport, options: ExportOptions): void {
  const timestamp = new Date().toISOString().slice(0, 10)
  const baseFilename = `code-review-${report.reviewId}-${timestamp}`

  switch (options.format) {
    case 'markdown': {
      const content = exportAsMarkdown(report, options)
      downloadFile(content, `${baseFilename}.md`, 'text/markdown')
      break
    }
    case 'json': {
      const content = exportAsJSON(report, options)
      downloadFile(content, `${baseFilename}.json`, 'application/json')
      break
    }
    case 'html': {
      const content = exportAsHTML(report, options)
      downloadFile(content, `${baseFilename}.html`, 'text/html')
      break
    }
  }
}

// Batch export
export function batchExport(reports: ReviewReport[], options: ExportOptions): void {
  reports.forEach(report => exportReport(report, options))
}
